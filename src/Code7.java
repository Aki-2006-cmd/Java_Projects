// Logical Operators

public class Code7 {
    public static void main (String[] a){

        // AND   -  &
        // OR    -  |
        // NOT   -  !

        int x = 1;
        int y = 2;
        int z = 3;
        int b = 4;

        boolean result = x > y | z > b ;
        System.out.println(result);

        boolean result2 = !( x > y ) ;
        System.out.println(result2);




    }
}
